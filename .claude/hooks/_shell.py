"""훅들이 셸 명령을 읽을 때 공유하는 것. **훅이 아니다** (밑줄로 구분).

여기 있는 것은 하나뿐이다: **히어독 본문은 명령이 아니라 데이터다.**

훅은 Bash 도구가 실행할 명령 문자열을 통째로 받는다. 그 안에는 히어독으로 넘긴
커밋 메시지·PR 본문·스크립트가 **글자 그대로** 들어 있고, 거기 적힌 `git commit`
이나 `gh pr create` 는 실행될 명령이 아니라 그것을 설명하는 문장이다. 구분하지
않으면 훅을 설명하는 글이 훅을 깨운다.

실제로 두 훅 모두 여기서 당했다 (→ `docs/12-harness.md` §4):

  review-on-pr.py    커밋 메시지에 "gh pr create 를 가로챈다" 라고 적었더니
                     shlex 가 gh·pr·create 를 각각 토큰으로 쪼갰다
  review-on-commit.py "이 훅은 git commit 을 가로챈다" 가 적힌 **무관한 명령**에서
                     정규식이 매칭돼, 산문을 플래그로 토큰화한 채 게이트가 돌았다.
                     낭비로 끝나지 않는다 — 그 뒤 리뷰가 현재 스테이지된 diff 로
                     돌아서 **관계없는 Bash 명령을 차단**한다

같은 것을 두 파일에 복사하면 한쪽만 고쳐진 상태가 생긴다. 이 레포는 그 실패를
반복해서 겪었고(`review-on-pr.py` 의 base 파싱이 최근 사례다), 그래서 여기 하나만
둔다. 판정 로직(구분자 절단 등)은 두 훅이 서로 다른 방식으로 이미 굳혀 놓았으므로
합치지 않는다 — 여기 모으는 것은 **양쪽이 글자 그대로 같아야 하는 것**뿐이다.
"""
from __future__ import annotations

import re

# `<<'TAG' … TAG` / `<<-TAG … TAG` / `<<"TAG" … TAG`.
# 끝 표식은 줄 하나를 통째로 차지하므로 뒤에 공백이나 문자열 끝이 온다.
HEREDOC_BODY = re.compile(r"<<-?\s*['\"]?(\w+)['\"]?\s*\n.*?\n\1(?=\s|$)",
                          re.DOTALL)

# 지운 자리에 남기는 표식. **평범한 단어를 쓰면 안 된다** — 본문에 그 단어가
# 리터럴로 들어 있으면 히어독이 있다고 오판한다. NUL 은 셸 명령 문자열에
# 들어올 수 없다.
STRIPPED = "\0heredoc\0"


def strip_heredocs(cmd: str) -> str:
    """히어독 **본문**을 지운다. 명령 부분은 그대로 남는다.

    매칭·토큰화는 이걸 거친 문자열로 한다. 본문 자체가 필요하면
    (PR 훅이 `--body "$(cat <<'EOF' … EOF)"` 에서 꺼낸다) 원본에서 따로 읽는다.
    """
    return HEREDOC_BODY.sub("<<" + STRIPPED, cmd)


# 셸 명령 구분자. 이 뒤는 **다른 명령**이라 앞 명령의 플래그 판정에 섞이면 안 된다.
# 쓰는 방법은 훅마다 다르다 — 커밋 훅은 따옴표 상태를 보며 문자열 단계에서 자르고,
# PR 훅은 shlex 의 punctuation_chars 로 토큰을 떼어낸다. 목록만 공유한다.
SEPARATORS = (";", "&&", "||", "|", "&")
